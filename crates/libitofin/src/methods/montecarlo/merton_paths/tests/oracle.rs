#[test]
fn stream_words_transforms_and_jump_counts_match_independent_fixture() {
    let expected = [
        (-0.31985239197154675, 1.0, -1.5924922285463126),
        (0.8293364834726858, 0.0, -0.13463759062854916),
        (1.6518193787298954, 1.0, 0.3255170771478866),
        (-0.9023526306658766, 0.0, -0.4906301803491114),
        (0.6188546400812096, 0.0, -0.044280788413889466),
        (0.7711500362518082, 0.0, 0.6917808538610539),
        (0.24987627978810856, 1.0, -0.056755773225366166),
        (0.24520245306794447, 0.0, -1.0920381783960909),
        (-1.0109564443577614, 0.0, 0.9979082350921727),
        (-0.13619703980908432, 1.0, 2.016776944151818),
        (-1.0110572131821498, 0.0, -0.17469003401683866),
        (-1.2816944810144082, 0.0, 0.7437027120568257),
    ];
    let mut draws = Draws::new(42, 0.25).unwrap();
    for (zd, count, zj) in expected {
        let (actual_zd, actual_count, actual_zj) = draws.next().unwrap();
        assert_close(actual_zd, zd, 2e-14);
        assert_eq!(actual_count, count);
        assert_close(actual_zj, zj, 2e-14);
    }
    let words = [
        [1608637542, 3915449494, 238959412],
        [3421126067, 1922758419, 1917484754],
        [4083286876, 3793001662, 2695543465],
        [787846414, 1292008319, 1339359860],
        [3143890026, 497193590, 2071635782],
        [3348747335, 422964674, 3244686812],
        [2571218620, 3859116204, 2050287990],
        [2563451924, 3340158409, 590163555],
        [670094950, 3196662619, 3611372014],
        [1914837113, 3626724470, 4201081896],
        [669991378, 903544153, 1849677485],
        [429389014, 678563324, 3313446262],
    ];
    let mut diffusion = MersenneTwisterUniformRng::new(42);
    let mut poisson = MersenneTwisterUniformRng::new(2654435811);
    let mut jump = MersenneTwisterUniformRng::new(3144134319);
    for expected in words {
        assert_eq!(
            [diffusion.next_u32(), poisson.next_u32(), jump.next_u32()],
            expected
        );
    }
}
